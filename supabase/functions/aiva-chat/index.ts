import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { messages, location } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const systemPrompt = `You are AIVA, the USPS Virtual Assistant inside a Self-Operating Post Office kiosk.

The user's current location is: ${location || "unknown"}.

Answer USPS questions directly and confidently. Be specific and give real numbers, prices, and times. Do NOT tell the user to "check usps.com" or "visit a branch" — YOU are their assistant, give them the answer.

Examples:
- For hours: give the actual hours for their location's typical Post Office (lobby self-service is often 24/7; retail counter is usually Mon-Fri 9-5, Sat 9-1, closed Sun).
- For shipping prices: give a real quote. Use current USPS rates: USPS Ground Advantage from $5.50 (1lb local) to ~$12 cross-country; Priority Mail Flat Rate small box $11.30, medium $20.10, large $26.95; First-Class letter stamp $0.78. Ask for weight/destination if needed for a precise quote, but always give a useful estimate.
- For tracking, holds, forwarding: explain the steps directly.

Keep replies short (2–4 sentences), warm, and practical. Use the user's location to make answers feel local. This is a demo, but answer like a real assistant.`;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: systemPrompt },
          ...messages,
        ],
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded, please try again in a moment." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted. Please add funds to your Lovable workspace." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const data = await response.json();
    const reply = data.choices?.[0]?.message?.content ?? "Sorry, I couldn't generate a response.";

    return new Response(JSON.stringify({ reply }), {
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (e) {
    console.error("aiva-chat error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
